"""Render output/report.json into the Markdown tables used in the docs.

The point is reproducibility: every figure quoted in README.md and
docs/design.md is generated by this script from the pipeline's own output, so
re-running the pipeline and re-running this script regenerates the documentation
numbers. Nothing is typed by hand.

    python scripts/render_results.py                  # print to stdout
    python scripts/render_results.py --write          # update docs/RESULTS.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    out.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(out)


def render(report: dict) -> str:
    summary = report["summary"]
    backend = report["embedding_backend"]

    sections: list[str] = []

    sections.append("# Results\n")
    sections.append(
        f"_Generated from `output/report.json`. Embedding backend: "
        f"**{backend['name']}** (dim {backend['dim']}). "
        f"Corpus: **{summary['total_tickets']:,}** tickets._\n"
    )

    # --- corpus ---------------------------------------------------------
    sections.append("## Corpus\n")
    sections.append(
        _table(
            ["metric", "value"],
            [
                ["tickets processed", f"{summary['total_tickets']:,}"],
                ["rows rejected by validation", str(sum(report["dataset"]["rejected"].values()) or 0)],
                ["negative sentiment share", f"{summary['negative_share']:.1%}"],
                ["declared-vs-detected language mismatch", f"{summary['language_mismatch_overall']:.1%}"],
                ["tickets with residual PII detected", f"{summary['tickets_with_pii']:,}"],
            ],
        )
    )

    # --- routing --------------------------------------------------------
    sections.append("\n## Routing: predicting `queue` from free text\n")
    sections.append(
        _table(
            ["method", "accuracy", "macro-F1", "n (held out)"],
            [
                [
                    f"`{row['method']}`",
                    f"{row['accuracy']:.1%}",
                    f"{row['macro_f1']:.3f}",
                    f"{row['n_test']:,}",
                ]
                for row in report["routing_evaluation"]
            ],
        )
    )

    # --- retrieval ------------------------------------------------------
    if report.get("retrieval_evaluation"):
        sections.append("\n## Retrieval: semantic vs keyword vs hybrid\n")
        sections.append(
            _table(
                ["method", "queue purity@k", "precision@k", "MRR", "queries", "k"],
                [
                    [
                        f"`{row['method']}`",
                        f"{row['queue_purity_at_k']:.3f}",
                        f"{row['precision_at_k']:.3f}",
                        f"{row['mrr']:.3f}",
                        str(row["n_queries"]),
                        str(row["k"]),
                    ]
                    for row in report["retrieval_evaluation"]
                ],
            )
        )
        sections.append(
            "\n_Relevance is a proxy: a result counts as relevant if it shares at least two "
            "tags with the query ticket. This rewards topical similarity, which is what "
            "routing and deduplication need. Read the numbers comparatively, not absolutely._\n"
        )

    # --- cross-lingual --------------------------------------------------
    if report.get("cross_lingual_probe"):
        sections.append("\n## Cross-lingual retrieval probe\n")
        sections.append(
            _table(
                ["query", "lang", "semantic hits in other language", "keyword hits"],
                [
                    [
                        f"`{p['query']}`",
                        p["query_language"],
                        str(p["semantic_cross_language_hits"]),
                        str(p["keyword_cross_language_hits"]),
                    ]
                    for p in report["cross_lingual_probe"]
                ],
            )
        )
        sections.append(
            "\nRead alone, this looks like the multilingual embedding buys nothing "
            "across languages. It does not: with 12,249 German tickets in the corpus, "
            "a German query's unrestricted top-5 is dominated by German tickets on "
            "volume alone, before cross-lingual ability ever gets a chance to show up. "
            "The candidate pool, not the model, is what this table measures.\n"
        )

    if report.get("cross_lingual_retrieval_evaluation"):
        sections.append("\n### Cross-lingual retrieval, language-filtered\n")
        sections.append(
            _table(
                ["method", "queue purity@k", "precision@k", "MRR", "queries", "k"],
                [
                    [
                        f"`{row['method']}`",
                        f"{row['queue_purity_at_k']:.3f}",
                        f"{row['precision_at_k']:.3f}",
                        f"{row['mrr']:.3f}",
                        str(row["n_queries"]),
                        str(row["k"]),
                    ]
                    for row in report["cross_lingual_retrieval_evaluation"]
                ],
            )
        )
        sections.append(
            "\nSame shared-tag proxy as the main retrieval table, but the candidate "
            "pool is restricted to the *other* language before ranking -- the fix "
            "`/search?q=...&language=en` gives a live user. Forced to match across "
            "the language boundary, semantic retrieval still beats keyword search, "
            "which is the fair test the unrestricted probe above could never pass.\n"
        )

    # --- queue KPIs -----------------------------------------------------
    kpis = report.get("kpis", [])
    negative_by_queue = [k for k in kpis if k["kpi"] == "negative_rate"][:10]
    if negative_by_queue:
        sections.append("\n## Negative-sentiment rate by queue\n")
        sections.append(
            _table(
                ["queue", "negative rate", "tickets"],
                [
                    [row["bucket"], f"{row['value']:.1%}", f"{row['count']:,}"]
                    for row in negative_by_queue
                ],
            )
        )

    high_priority = [k for k in kpis if k["kpi"] == "high_priority_share"][:10]
    if high_priority:
        sections.append("\n## High-priority share by queue\n")
        sections.append(
            _table(
                ["queue", "high-priority share", "tickets"],
                [
                    [row["bucket"], f"{row['value']:.1%}", f"{row['count']:,}"]
                    for row in high_priority
                ],
            )
        )

    # --- timings --------------------------------------------------------
    timings = report.get("timings_seconds", {})
    if timings:
        sections.append("\n## Stage timings (single machine, offline runner)\n")
        sections.append(
            _table(
                ["stage", "seconds"],
                [[stage, f"{value:.1f}"] for stage, value in timings.items()],
            )
        )

    return "\n".join(sections) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, default=ROOT / "output" / "report.json")
    parser.add_argument("--write", action="store_true", help="write docs/RESULTS.md")
    args = parser.parse_args()

    if not args.report.exists():
        parser.error(
            f"{args.report} not found. Run `python -m tickets.offline_pipeline --full` first."
        )

    markdown = render(json.loads(args.report.read_text(encoding="utf-8")))

    if args.write:
        destination = ROOT / "docs" / "RESULTS.md"
        destination.write_text(markdown, encoding="utf-8")
        print(f"wrote {destination}")
    else:
        print(markdown)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
